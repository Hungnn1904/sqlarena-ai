-- EnterpriseDB world schema for PostgreSQL
-- Run in a newly created database, e.g. enterprise_db.
-- The document provides suggested types and business rules; this DDL implements
-- structural keys and safe row-level checks. Cross-row rules need separate logic.
BEGIN;

CREATE TABLE customers (
 customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name VARCHAR(150) NOT NULL,
 email VARCHAR(255) NOT NULL UNIQUE,
 phone VARCHAR(20),
 gender VARCHAR(20),
 date_of_birth DATE,
 registered_at TIMESTAMP NOT NULL,
 status VARCHAR(20) NOT NULL
);
CREATE TABLE customer_addresses (
 address_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id INTEGER NOT NULL REFERENCES customers(customer_id),
 address_line VARCHAR(255) NOT NULL,
 city VARCHAR(100) NOT NULL,
 district VARCHAR(100) NOT NULL,
 postal_code VARCHAR(20),
 is_default BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP NOT NULL,
 UNIQUE (address_id, customer_id)
);
CREATE TABLE categories (
 category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category_name VARCHAR(100) NOT NULL,
 parent_category_id INTEGER REFERENCES categories(category_id),
 description TEXT,
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 CONSTRAINT chk_category_not_own_parent CHECK (parent_category_id IS NULL OR parent_category_id <> category_id)
);
CREATE TABLE suppliers (
 supplier_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 supplier_name VARCHAR(150) NOT NULL,
 contact_email VARCHAR(255),
 phone VARCHAR(20),
 country VARCHAR(100),
 joined_at DATE NOT NULL,
 status VARCHAR(20) NOT NULL
);
CREATE TABLE products (
 product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_name VARCHAR(200) NOT NULL,
 category_id INTEGER NOT NULL REFERENCES categories(category_id),
 supplier_id INTEGER NOT NULL REFERENCES suppliers(supplier_id),
 sku VARCHAR(50) NOT NULL UNIQUE,
 list_price NUMERIC(15,2) NOT NULL,
 cost_price NUMERIC(15,2) NOT NULL,
 created_at TIMESTAMP NOT NULL,
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 CONSTRAINT chk_product_prices CHECK (list_price >= 0 AND cost_price >= 0)
);
CREATE TABLE departments (
 department_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 department_name VARCHAR(150) NOT NULL,
 manager_employee_id INTEGER,
 created_at DATE NOT NULL,
 status VARCHAR(20) NOT NULL
);
CREATE TABLE employees (
 employee_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name VARCHAR(150) NOT NULL,
 department_id INTEGER NOT NULL REFERENCES departments(department_id),
 manager_id INTEGER REFERENCES employees(employee_id),
 hire_date DATE NOT NULL,
 job_title VARCHAR(100) NOT NULL,
 current_salary NUMERIC(15,2) NOT NULL,
 status VARCHAR(20) NOT NULL,
 CONSTRAINT chk_employee_not_own_manager CHECK (manager_id IS NULL OR manager_id <> employee_id),
 CONSTRAINT chk_employee_salary CHECK (current_salary >= 0)
);
-- Circular relationship: departments -> employees -> departments.
ALTER TABLE departments ADD CONSTRAINT fk_departments_manager
 FOREIGN KEY (manager_employee_id) REFERENCES employees(employee_id);
CREATE TABLE warehouses (
 warehouse_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 warehouse_name VARCHAR(150) NOT NULL,
 city VARCHAR(100) NOT NULL,
 capacity INTEGER NOT NULL,
 manager_employee_id INTEGER REFERENCES employees(employee_id),
 status VARCHAR(20) NOT NULL,
 CONSTRAINT chk_warehouse_capacity CHECK (capacity >= 0)
);
CREATE TABLE orders (
 order_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id INTEGER NOT NULL REFERENCES customers(customer_id),
 employee_id INTEGER REFERENCES employees(employee_id),
 shipping_address_id INTEGER NOT NULL,
 warehouse_id INTEGER REFERENCES warehouses(warehouse_id),
 order_date TIMESTAMP NOT NULL,
 status VARCHAR(30) NOT NULL,
 total_amount NUMERIC(15,2) NOT NULL,
 shipping_fee NUMERIC(15,2) NOT NULL,
 carrier_name VARCHAR(100),
 shipped_at TIMESTAMP,
 delivered_at TIMESTAMP,
 created_at TIMESTAMP NOT NULL,
 CONSTRAINT fk_orders_shipping_address_customer
   FOREIGN KEY (shipping_address_id, customer_id)
   REFERENCES customer_addresses(address_id, customer_id),
 CONSTRAINT chk_orders_amounts CHECK (total_amount >= 0 AND shipping_fee >= 0)
);
CREATE TABLE order_items (
 order_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id INTEGER NOT NULL REFERENCES orders(order_id),
 product_id INTEGER NOT NULL REFERENCES products(product_id),
 quantity INTEGER NOT NULL,
 unit_price NUMERIC(15,2) NOT NULL,
 discount_amount NUMERIC(15,2) NOT NULL DEFAULT 0,
 line_total NUMERIC(15,2) NOT NULL,
 CONSTRAINT chk_order_items_values CHECK (
  quantity > 0 AND unit_price >= 0 AND discount_amount >= 0
  AND discount_amount <= quantity * unit_price
  AND line_total = quantity * unit_price - discount_amount
 )
);
CREATE TABLE order_status_history (
 history_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id INTEGER NOT NULL REFERENCES orders(order_id),
 old_status VARCHAR(30),
 new_status VARCHAR(30) NOT NULL,
 changed_at TIMESTAMP NOT NULL,
 changed_by_employee_id INTEGER REFERENCES employees(employee_id)
);
CREATE TABLE inventory_transactions (
 transaction_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id INTEGER NOT NULL REFERENCES products(product_id),
 warehouse_id INTEGER NOT NULL REFERENCES warehouses(warehouse_id),
 transaction_type VARCHAR(30) NOT NULL,
 quantity_change INTEGER NOT NULL,
 transaction_date TIMESTAMP NOT NULL,
 reference_type VARCHAR(30),
 reference_id INTEGER,
 note TEXT
 -- reference_type + reference_id is polymorphic metadata, not a conventional FK.
);
CREATE TABLE salary_history (
 salary_history_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 employee_id INTEGER NOT NULL REFERENCES employees(employee_id),
 old_salary NUMERIC(15,2) NOT NULL,
 new_salary NUMERIC(15,2) NOT NULL,
 effective_date DATE NOT NULL,
 change_reason VARCHAR(150) NOT NULL,
 CONSTRAINT chk_salary_history_amounts CHECK (old_salary >= 0 AND new_salary >= 0)
);
CREATE TABLE payments (
 payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id INTEGER NOT NULL REFERENCES orders(order_id),
 amount NUMERIC(15,2) NOT NULL,
 payment_method VARCHAR(30) NOT NULL,
 payment_status VARCHAR(30) NOT NULL,
 attempted_at TIMESTAMP NOT NULL,
 completed_at TIMESTAMP,
 transaction_code VARCHAR(100),
 CONSTRAINT chk_payment_amount CHECK (amount >= 0)
);
CREATE TABLE refunds (
 refund_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 payment_id INTEGER NOT NULL REFERENCES payments(payment_id),
 refund_amount NUMERIC(15,2) NOT NULL,
 refund_reason VARCHAR(150) NOT NULL,
 refund_status VARCHAR(30) NOT NULL,
 requested_at TIMESTAMP NOT NULL,
 completed_at TIMESTAMP,
 CONSTRAINT chk_refund_amount CHECK (refund_amount > 0)
);
CREATE TABLE operating_expenses (
 expense_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 department_id INTEGER REFERENCES departments(department_id),
 expense_category VARCHAR(100) NOT NULL,
 amount NUMERIC(15,2) NOT NULL,
 expense_date DATE NOT NULL,
 description TEXT,
 approved_by_employee_id INTEGER REFERENCES employees(employee_id),
 CONSTRAINT chk_expense_amount CHECK (amount >= 0)
);

-- Common join-path indexes (PK and UNIQUE already create indexes).
CREATE INDEX idx_customer_addresses_customer ON customer_addresses(customer_id);
CREATE INDEX idx_products_category ON products(category_id);
CREATE INDEX idx_products_supplier ON products(supplier_id);
CREATE INDEX idx_employees_department ON employees(department_id);
CREATE INDEX idx_employees_manager ON employees(manager_id);
CREATE INDEX idx_orders_customer ON orders(customer_id);
CREATE INDEX idx_orders_employee ON orders(employee_id);
CREATE INDEX idx_orders_warehouse ON orders(warehouse_id);
CREATE INDEX idx_order_items_order ON order_items(order_id);
CREATE INDEX idx_order_items_product ON order_items(product_id);
CREATE INDEX idx_order_status_history_order ON order_status_history(order_id);
CREATE INDEX idx_inventory_transactions_product_warehouse ON inventory_transactions(product_id, warehouse_id);
CREATE INDEX idx_salary_history_employee ON salary_history(employee_id);
CREATE INDEX idx_payments_order ON payments(order_id);
CREATE INDEX idx_refunds_payment ON refunds(payment_id);
CREATE INDEX idx_operating_expenses_department ON operating_expenses(department_id);

COMMIT;

-- Business rules not fully enforced by this DDL:
-- 1) orders.total_amount = SUM(order_items.line_total) + orders.shipping_fee.
-- 2) Exactly one default address per customer (if required by application).
-- 3) Active departments have a designated manager; management tree must be acyclic;
--    direct manager belongs to the same department.
-- 4) employees.current_salary agrees with latest effective salary_history.
-- 5) Refunds must refer to successful payments; total successful refunds
--    cannot exceed successful payment amount.
-- 6) inventory balance depends on full transaction history or opening balance.
-- 7) Status-transition correctness and shipment timing require application logic.

-- Sửa bảng inventory_transactions
BEGIN;

-- 1. Thêm cột liên kết đến dòng đơn hàng
ALTER TABLE inventory_transactions
ADD COLUMN order_item_id INT;

-- 2. Tạo khóa ngoại
ALTER TABLE inventory_transactions
ADD CONSTRAINT fk_inventory_order_item
FOREIGN KEY (order_item_id)
REFERENCES order_items(order_item_id);

-- 3. Bỏ hai cột tham chiếu cũ
ALTER TABLE inventory_transactions
DROP COLUMN reference_type,
DROP COLUMN reference_id;

COMMIT;

--bỏ cột completed_at ở payments
ALTER TABLE payments
DROP COLUMN IF EXISTS completed_at;

--bỏ cột old_salary và sửa new_salary thành salary ở salary_history
BEGIN;

-- 1. Đổi new_salary thành salary
-- Drop the original check before removing old_salary. The check references
-- both old_salary and new_salary, so dropping old_salary first breaks a clean run.
ALTER TABLE salary_history
DROP CONSTRAINT IF EXISTS chk_salary_history_amounts;

ALTER TABLE salary_history
RENAME COLUMN new_salary TO salary;

-- 2. Xóa old_salary
ALTER TABLE salary_history
DROP COLUMN old_salary;

-- 3. Mỗi mức lương phải lớn hơn 0
ALTER TABLE salary_history
ADD CONSTRAINT chk_salary_history_positive
CHECK (salary > 0);

-- 4. Một nhân viên không được có hai bản ghi
-- cùng ngày bắt đầu áp dụng lương
ALTER TABLE salary_history
ADD CONSTRAINT uq_salary_history_employee_date
UNIQUE (employee_id, effective_date);

COMMIT;

