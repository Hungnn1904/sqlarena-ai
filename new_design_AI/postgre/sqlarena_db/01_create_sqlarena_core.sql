BEGIN;

CREATE SCHEMA IF NOT EXISTS draft;

-- =====================================================
-- 1. QUESTION_DRAFTS
-- Lưu câu hỏi AI sinh ra
-- =====================================================

CREATE TABLE IF NOT EXISTS draft.question_drafts (
    draft_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    world_id VARCHAR(100) NOT NULL,

    question TEXT NOT NULL,
    schema_text TEXT NOT NULL DEFAULT '',

    compare_mode VARCHAR(30) NOT NULL DEFAULT 'unordered',

    difficulty VARCHAR(10) NOT NULL,

    skills JSONB NOT NULL DEFAULT '[]'::jsonb,
    traps JSONB NOT NULL DEFAULT '[]'::jsonb,

    parent_ids JSONB NOT NULL DEFAULT '[]'::jsonb,
    depth INTEGER NOT NULL DEFAULT 1,

    status VARCHAR(20) NOT NULL DEFAULT 'pending',

    gen_model VARCHAR(100),
    gen_prompt_version VARCHAR(50),

    retry_count INTEGER NOT NULL DEFAULT 0,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_draft_world
        FOREIGN KEY (world_id)
        REFERENCES core.worlds(world_id),

    CONSTRAINT chk_draft_difficulty
        CHECK (difficulty IN ('easy', 'medium', 'hard')),

    CONSTRAINT chk_draft_status
        CHECK (
            status IN (
                'pending',
                'reviewing',
                'approved',
                'rejected',
                'needs_human'
            )
        ),

    CONSTRAINT chk_draft_depth
        CHECK (depth >= 0),

    CONSTRAINT chk_draft_retry_count
        CHECK (retry_count >= 0),

    CONSTRAINT chk_draft_compare_mode
        CHECK (compare_mode IN ('ordered', 'unordered'))
);

-- =====================================================
-- 2. REVIEW_LOGS
-- Lưu lịch sử kiểm duyệt câu hỏi
-- =====================================================

CREATE TABLE IF NOT EXISTS draft.review_logs (
    log_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    draft_id BIGINT NOT NULL,

    stage VARCHAR(30) NOT NULL,

    passed BOOLEAN,

    score NUMERIC(5,2),

    reasons JSONB NOT NULL DEFAULT '[]'::jsonb,

    review_model VARCHAR(100),

    raw_output JSONB,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_review_draft
        FOREIGN KEY (draft_id)
        REFERENCES draft.question_drafts(draft_id)
        ON DELETE CASCADE,

    CONSTRAINT chk_review_stage
        CHECK (
            stage IN (
                'code_check',
                'self_solve',
                'checklist'
            )
        ),

    CONSTRAINT chk_review_score
        CHECK (score IS NULL OR score BETWEEN 0 AND 100)
);

-- =====================================================
-- 3. SELF_SOLVE_RUNS
-- Lưu kết quả Model B tự giải đề
-- =====================================================

CREATE TABLE IF NOT EXISTS draft.self_solve_runs (
    run_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    draft_id BIGINT NOT NULL,

    model_sql TEXT,

    matched_datasets JSONB NOT NULL DEFAULT '[]'::jsonb,

    mismatch_detail JSONB,

    CONSTRAINT fk_self_solve_draft
        FOREIGN KEY (draft_id)
        REFERENCES draft.question_drafts(draft_id)
        ON DELETE CASCADE
);

-- =====================================================
-- 4. INDEXES
-- =====================================================

CREATE INDEX IF NOT EXISTS idx_draft_world
ON draft.question_drafts(world_id);

CREATE INDEX IF NOT EXISTS idx_draft_status
ON draft.question_drafts(status);

CREATE INDEX IF NOT EXISTS idx_draft_difficulty
ON draft.question_drafts(difficulty);

CREATE INDEX IF NOT EXISTS idx_review_draft
ON draft.review_logs(draft_id);

CREATE INDEX IF NOT EXISTS idx_self_solve_draft
ON draft.self_solve_runs(draft_id);

COMMIT;


